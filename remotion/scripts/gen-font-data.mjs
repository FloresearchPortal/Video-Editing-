// Embeds the Poppins faces into the bundle as base64 (src/series/flostocks/fontData.gen.ts) so fonts
// load from memory in every render tab: no network fetch that a busy WebGL tab could starve.
import { readFileSync, writeFileSync } from 'fs';
import { fileURLToPath } from 'url';
import path from 'path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, '..', 'media', 'series', 'flostocks', 'fonts');
const faces = [
  ['Poppins-Black.ttf', '900', 'normal'], ['Poppins-BlackItalic.ttf', '900', 'italic'],
  ['Poppins-ExtraBold.ttf', '800', 'normal'], ['Poppins-Bold.ttf', '700', 'normal'],
  ['Poppins-SemiBold.ttf', '600', 'normal'], ['Poppins-SemiBoldItalic.ttf', '600', 'italic'],
  ['Poppins-Medium.ttf', '500', 'normal'], ['Poppins-MediumItalic.ttf', '500', 'italic'],
  ['Poppins-Regular.ttf', '400', 'normal'], ['Poppins-Italic.ttf', '400', 'italic'],
];
let out = '// AUTO-GENERATED by scripts/gen-font-data.mjs — do not edit, do not commit.\n';
out += 'export const FONT_DATA: [string, string, string][] = [\n';
for (const [file, w, st] of faces) out += `  ['${w}', '${st}', '${readFileSync(path.join(dir, file)).toString('base64')}'],\n`;
out += '];\n';
writeFileSync(path.join(root, 'src', 'series', 'flostocks', 'fontData.gen.ts'), out);
console.log('font data ->', faces.length, 'faces');
